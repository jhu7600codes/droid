import java.io.File;
import java.io.FileWriter;
import java.lang.reflect.Method;
import java.lang.reflect.Modifier;

/**
 * Writes droid.defaults.Default<Name>: an implementation of a system service interface where every
 * method does nothing (returns false / 0 / null). droid's services (tools/aosp/system) extend these
 * and override what an app needs. Usage: GenDefaults <outDir> <interface>[=<base class>] ...
 * Without a base class the interface's Stub is the base.
 */
public class GenDefaults {
    public static void main(String[] args) throws Exception {
        File out = new File(args[0], "droid/defaults");
        out.mkdirs();
        ClassLoader cl = GenDefaults.class.getClassLoader();
        for (int i = 1; i < args.length; i++) {
            String spec = args[i];
            String ifName = spec.contains("=") ? spec.substring(0, spec.indexOf('=')) : spec;
            Class<?> iface = Class.forName(ifName, false, cl);
            Class<?> base = spec.contains("=") ? Class.forName(spec.substring(spec.indexOf('=') + 1), false, cl) : Class.forName(ifName + "$Stub", false, cl);
            String name = "Default" + iface.getSimpleName();
            StringBuilder sb = new StringBuilder();
            sb.append("package droid.defaults;\n\n// generated by tools/aosp/gen/GenDefaults.java: every method does nothing\n@SuppressWarnings({\"rawtypes\", \"unchecked\"})\n");
            sb.append("public class ").append(name).append(" extends ").append(base.getCanonicalName()).append(" {\n");
            for (Method m : iface.getMethods()) {
                if (Modifier.isStatic(m.getModifiers()) || m.getName().equals("asBinder")) continue;
                try { Method b = base.getMethod(m.getName(), m.getParameterTypes()); if (!Modifier.isAbstract(b.getModifiers())) continue; } catch (NoSuchMethodException e) { /* write it */ }
                Class<?> r = m.getReturnType();
                sb.append("    public ").append(r.getCanonicalName()).append(' ').append(m.getName()).append('(');
                Class<?>[] ps = m.getParameterTypes();
                for (int k = 0; k < ps.length; k++) { if (k > 0) sb.append(", "); sb.append(ps[k].getCanonicalName()).append(" p").append(k); }
                sb.append(')');
                if (m.getExceptionTypes().length > 0) {
                    sb.append(" throws ");
                    Class<?>[] ex = m.getExceptionTypes();
                    for (int k = 0; k < ex.length; k++) { if (k > 0) sb.append(", "); sb.append(ex[k].getCanonicalName()); }
                }
                String ret = r == void.class ? "" : r == boolean.class ? " return false;" : r.isPrimitive() ? " return (" + r.getName() + ") 0;" : " return null;";
                sb.append(" {").append(ret).append(" }\n");
            }
            sb.append("}\n");
            try (FileWriter w = new FileWriter(new File(out, name + ".java"))) { w.write(sb.toString()); }
        }
    }
}
