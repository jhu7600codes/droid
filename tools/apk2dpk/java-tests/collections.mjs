// checks the java.util shims behave like java (run with node)
import { VM, JObject } from '../../../src/runtime/android/dalvik.ts'
import { registerJava, box } from '../../../src/runtime/android/java.ts'
import { registerCollections } from '../../../src/runtime/android/collections.ts'
const vm = new VM(); registerJava(vm); registerCollections(vm)
const call = (o, k, a = []) => vm.callVirtual(o, k, a)
const st = (c, k, a = []) => vm.callStatic(c, k, a)
const I = (n) => box(vm, 'Ljava/lang/Integer;', n)
let fails = 0
const ok = (c, msg) => { if (!c) fails++; console.log((c ? 'ok   ' : 'FAIL ') + msg) }
const m = vm.newObject('Ljava/util/HashMap;')
call(m, 'put(Ljava/lang/Object;Ljava/lang/Object;)Ljava/lang/Object;', ['a', I(1)])
call(m, 'put(Ljava/lang/Object;Ljava/lang/Object;)Ljava/lang/Object;', [I(7), 'seven'])
ok(call(m, 'get(Ljava/lang/Object;)Ljava/lang/Object;', [I(7)]) === 'seven', 'boxed keys compare by value')
const ks = call(m, 'keySet()Ljava/util/Set;')
ok(call(ks, 'size()I') === 2 && call(ks, 'contains(Ljava/lang/Object;)Z', ['a']) === 1, 'keySet view')
const es = call(m, 'entrySet()Ljava/util/Set;'), it = call(es, 'iterator()Ljava/util/Iterator;')
const e = call(it, 'next()Ljava/lang/Object;'); call(e, 'setValue(Ljava/lang/Object;)Ljava/lang/Object;', [I(42)])
ok(call(call(m, 'get(Ljava/lang/Object;)Ljava/lang/Object;', ['a']), 'intValue()I') === 42, 'entry.setValue writes through')
call(ks, 'remove(Ljava/lang/Object;)Z', ['a'])
ok(call(m, 'size()I') === 1, 'removing from keySet removes from the map')
const s = vm.newObject('Ljava/util/HashSet;')
for (const x of ['x', 'y', 'x']) call(s, 'add(Ljava/lang/Object;)Z', [x])
ok(call(s, 'size()I') === 2, 'set dedupes')
const t = vm.newObject('Ljava/util/TreeMap;')
for (const k of ['pear', 'apple', 'fig']) call(t, 'put(Ljava/lang/Object;Ljava/lang/Object;)Ljava/lang/Object;', [k, k.length])
ok(call(t, 'firstKey()Ljava/lang/Object;') === 'apple' && call(t, 'toString()Ljava/lang/String;') === '{apple=5, fig=3, pear=4}', 'tree map sorted: ' + call(t, 'toString()Ljava/lang/String;'))
const l = vm.newObject('Ljava/util/ArrayList;')
for (const x of ['c', 'a', 'b']) call(l, 'add(Ljava/lang/Object;)Z', [x])
st('Ljava/util/Collections;', 'sort(Ljava/util/List;)V', [l])
ok(call(l, 'toString()Ljava/lang/String;') === '[a, b, c]', 'Collections.sort')
const sm = st('Ljava/util/Collections;', 'synchronizedMap(Ljava/util/Map;)Ljava/util/Map;', [m])
ok(sm === m, 'synchronizedMap')
const dq = vm.newObject('Ljava/util/ArrayDeque;'); call(dq, 'push(Ljava/lang/Object;)V', ['1']); call(dq, 'addLast(Ljava/lang/Object;)V', ['2'])
ok(call(dq, 'pollFirst()Ljava/lang/Object;') === '1' && call(dq, 'pollFirst()Ljava/lang/Object;') === '2', 'deque')
console.log(fails ? fails + ' FAILED' : 'ALL OK')
