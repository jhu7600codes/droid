// milestone 3: skip setup, open the sample apps
export default async ({ page, shot, base }) => {
  await page.goto(base + 'index.html?fastboot')
  await page.evaluate(() => { localStorage.setItem('droid.settings', JSON.stringify({ 'setup.done': true, 'lock.type': 'none' })) })
  await page.reload()
  await page.waitForTimeout(2500)
  await page.click('.allapps')
  await shot('m3-01-allapps')
  await page.click('.l-grid .ic[data-pkg="com.droid.hello"]')
  await page.waitForTimeout(1200)
  const f = page.frameLocator('.window.visible iframe')
  await f.locator('#b').click()
  await shot('m3-02-hello')
  await page.evaluate(() => window.droid_shell.wm.home())
  await page.click('.allapps')
  await page.click('.l-grid .ic[data-pkg="com.droid.notes"]')
  await page.waitForTimeout(1200)
  await page.click('.window.visible .h-ab-overflow')
  await shot('m3-03-notes-menu')
  await page.click('.ab-menu span:first-child')
  await page.waitForTimeout(1200)
  await page.frameLocator('.window.visible iframe').locator('#t').fill('buy bread\nand milk')
  await shot('m3-04-edit')
  await page.evaluate(() => window.droid_shell.wm.back())
  await page.waitForTimeout(800)
  await shot('m3-05-perm-dialog')
  await page.click('#overlay .h-btn-borderless:last-child').catch(() => {})
  await page.waitForTimeout(1000)
  await shot('m3-06-notes-list')
  await page.evaluate(() => window.droid_shell.wm.home())
  await page.click('.allapps')
  await page.click('.l-grid .ic[data-pkg="com.droid.wasmdemo"]')
  await page.waitForTimeout(1500)
  await shot('m3-07-wasm')
}
