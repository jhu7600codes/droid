// milestone 9: clock, calculator, live wallpaper, system update, then the whole thing offline
export default async ({ page, shot, base }) => {
  await page.goto(base + 'index.html?fastboot&sw')
  await page.evaluate(() => localStorage.setItem('droid.settings', JSON.stringify({ 'setup.done': true, 'lock.type': 'none', wallpaper: 'live:spectrum' })))
  await page.reload()
  await page.waitForTimeout(3000)
  await shot('m9-01-live-wallpaper')
  await page.evaluate(() => { window.droid_shell.wm.start({ package: 'droid.deskclock', action: 'main' }) })
  await page.waitForTimeout(800)
  await shot('m9-02-clock')
  await page.evaluate(() => { window.droid_shell.wm.start({ package: 'droid.calculator', action: 'main' }) })
  await page.waitForTimeout(600)
  for (const k of ['7', '×', '6', '−', '2']) await page.click(`.window.visible .calc-key:text-is("${k}")`)
  await shot('m9-03-calc')
  await page.evaluate(() => { window.droid_shell.wm.start({ action: 'system-update' }) })
  await page.waitForTimeout(2500)
  await shot('m9-04-update')
  // offline: wait for the service worker, download essential, go offline, reload
  await page.evaluate(async () => { await navigator.serviceWorker.ready })
  await page.waitForFunction(() => JSON.parse(localStorage.getItem('droid.settings'))['offline.level'] === 'essential', null, { timeout: 60000 }).catch(() => console.log('download not finished'))
  await page.context().setOffline(true)
  await page.reload()
  await page.waitForTimeout(4000)
  await shot('m9-05-offline-boot')
  await page.evaluate(() => { window.droid_shell.wm.start({ action: 'view', data: 'https://example.com/' }) })
  await page.waitForTimeout(1500)
  await shot('m9-06-offline-browser')
  await page.context().setOffline(false)
}
