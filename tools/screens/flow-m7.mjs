// milestone 7: desktop mode at 1280x800 with a mouse, then tablet at 1024x768 touch-like (forced)
export default async ({ page, shot, base }) => {
  await page.goto(base + 'index.html?fastboot')
  await page.evaluate(() => localStorage.setItem('droid.settings', JSON.stringify({ 'setup.done': true, 'lock.type': 'none', 'screen.form': 'desktop' })))
  await page.reload()
  await page.waitForTimeout(2500)
  await shot('m7-01-desktop')
  await page.click('.tb-start')
  await page.waitForTimeout(400)
  await shot('m7-02-start')
  await page.click('.l-drawer .ic[data-pkg="droid.settings"]')
  await page.waitForTimeout(800)
  await page.click('.tb-start')
  await page.click('.l-drawer .ic[data-pkg="com.droid.notes"]')
  await page.waitForTimeout(1200)
  await page.click('.tb-start')
  await page.click('.l-drawer .ic[data-pkg="droid.browser"]')
  await page.waitForTimeout(1000)
  await shot('m7-03-windows')
  await page.locator('.window.visible .h-item:has-text("Display")').first().click().catch(() => {})
  const bar = page.locator('.dwin').first().locator('.dw-bar')
  const box = await bar.boundingBox()
  await page.mouse.move(box.x + 100, box.y + 10); await page.mouse.down(); await page.mouse.move(box.x + 300, box.y + 120, { steps: 6 }); await page.mouse.up()
  await shot('m7-04-dragged')
  await page.evaluate(() => { const s = window.droid_shell.settings; s.set('screen.form', 'tablet') })
  await page.waitForTimeout(800)
  await page.evaluate(() => window.droid_shell.wm.home())
  await page.waitForTimeout(500)
  await shot('m7-05-tablet-home')
  await page.evaluate(() => { window.droid_shell.wm.start({ action: 'settings' }) })
  await page.waitForTimeout(800)
  await page.locator('.window.visible .h-item:has-text("Display")').first().click()
  await page.waitForTimeout(400)
  await shot('m7-06-tablet-settings')
}
