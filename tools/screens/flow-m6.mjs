export default async ({ page, shot, base }) => {
  await page.goto(base + 'index.html?fastboot')
  await page.evaluate(() => localStorage.setItem('droid.settings', JSON.stringify({ 'setup.done': true, 'lock.type': 'none', 'samples.installed': true })))
  await page.reload()
  await page.waitForTimeout(2500)
  await page.evaluate(() => { window.droid_shell.wm.start({ action: 'store' }) })
  await page.waitForTimeout(1500)
  await shot('m6-01-store')
  await page.click('.window.visible .st-card:has-text("Notes")')
  await page.waitForTimeout(600)
  await shot('m6-02-listing')
  await page.click('.window.visible .st-primary')
  await page.waitForTimeout(500)
  await shot('m6-03-perms')
  await page.click('#overlay .h-btn-borderless:last-child')
  await page.waitForTimeout(2000)
  await shot('m6-04-installed')
  await page.evaluate(() => { window.droid_shell.wm.start({ action: 'danen-account' }) })
  await page.waitForTimeout(800)
  await shot('m6-05-account')
}
