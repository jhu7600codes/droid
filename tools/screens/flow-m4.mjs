const open = async (page, pkg) => {
  await page.evaluate(() => window.droid_shell.wm.home())
  await page.waitForTimeout(300)
  await page.click('.allapps')
  await page.click(`.l-grid .ic[data-pkg="${pkg}"]`)
  await page.waitForTimeout(900)
}
export default async ({ page, shot, base }) => {
  await page.goto(base + 'index.html?fastboot')
  await page.evaluate(() => localStorage.setItem('droid.settings', JSON.stringify({ 'setup.done': true, 'lock.type': 'none', 'location.pretend': { lat: 55.7558, lon: 37.6173 }, 'net.saved': ['jhfi'] })))
  await page.reload()
  await page.waitForTimeout(2500)
  await shot('m4-00-home')
  await open(page, 'droid.settings')
  await shot('m4-01-settings')
  await page.locator('.window.visible .h-item:has-text("Display")').click()
  await shot('m4-02-display')
  await page.evaluate(() => window.droid_shell.wm.back())
  await page.locator('.window.visible .h-item:has-text("About phone")').click()
  await shot('m4-03-about')
  await page.evaluate(() => window.droid_shell.wm.back())
  await page.locator('.window.visible .h-item:has-text("Wi-Fi")').first().click()
  await page.waitForTimeout(800)
  await shot('m4-04-wifi')
  await open(page, 'droid.camera')
  await page.waitForTimeout(1500)
  await shot('m4-05-camera')
  await page.click('.cam-shutter')
  await page.waitForTimeout(1200)
  await page.click('.cam-shutter')
  await page.waitForTimeout(800)
  await open(page, 'droid.gallery')
  await shot('m4-06-gallery')
  await page.click('.window.visible .g-album')
  await page.waitForTimeout(600)
  await page.click('.window.visible .g-cell')
  await page.waitForTimeout(800)
  await shot('m4-07-viewer')
  await open(page, 'droid.files')
  await page.locator('.window.visible .h-item:has-text("dcim")').click()
  await page.waitForTimeout(400)
  await page.locator('.window.visible .h-item:has-text("camera")').click()
  await page.waitForTimeout(600)
  await shot('m4-08-files')
}
