export default async ({ page, shot, base }) => {
  await page.goto(base + 'index.html')
  await page.waitForTimeout(2500)
  await shot('01-boot')
  await page.waitForTimeout(7500)
  await shot('02-wizard-welcome')
  await page.click('.wiz-start')
  await shot('03-wizard-network')
  for (let i = 0; i < 6; i++) { await page.click('.wiz-nav-btn.next'); await page.waitForTimeout(300); if (i === 0) await shot('04-wizard-account') }
  await shot('05-wizard-offline')
  await page.click('.wiz-nav-btn.next')
  await page.click('.wiz-start')
  await page.waitForTimeout(600)
  await shot('06-home')
  await page.mouse.move(300, 5); await page.mouse.down(); await page.mouse.move(300, 400, { steps: 8 }); await page.mouse.up()
  await shot('07-shade-qs')
  await page.evaluate(() => window.droid_shell.wm.back())
  await page.click('.allapps')
  await shot('08-allapps')
  await page.evaluate(() => window.droid_shell.wm.home())
  await page.evaluate(() => { document.dispatchEvent(new Event('visibilitychange')); })
  await page.evaluate(() => { const s = window.droid_shell.settings; s.set('owner.name', 'jhu') })
  await page.reload()
  await page.waitForTimeout(10000)
  await shot('09-lockscreen')
}
