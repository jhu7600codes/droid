// droid keyboard: type into a shell field (danen sign in) and into a dpk app (notes)
export default async ({ page, shot, base }) => {
  page.on('console', (m) => { if (m.type() === 'error' || /ime/i.test(m.text())) console.log('console:', m.text().slice(0, 200)) })
  page.on('pageerror', (e) => console.log('pageerror', e.message))
  await page.goto(base + 'index.html?fastboot')
  await page.evaluate(() => localStorage.setItem('droid.settings', JSON.stringify({ 'setup.done': true, 'lock.type': 'none', ime: 'droid' })))
  await page.reload(); await page.waitForTimeout(2500)
  await page.evaluate(() => window.droid_shell.wm.start({ action: 'danen-account' }))
  await page.waitForTimeout(1200)
  const w = page.locator('.window.visible')
  if (process.env.TOUCH) await w.locator('input[placeholder=Username]').tap(); else await w.locator('input[placeholder=Username]').click()
  await page.waitForTimeout(500)
  const tap = async (label) => { const k = page.locator('#ime .ime-key', { hasText: new RegExp('^' + label.replace(/[?.]/g, '\\$&') + '$', 'i') }).first(); if (process.env.TOUCH) await k.tap(); else await k.click() }
  for (const c of 'pigeon') await tap(c)
  await shot('ime-01-shell')
  console.log('shell value:', await w.locator('input[placeholder=Username]').inputValue())
  await page.locator('#ime .ime-key', { hasText: '?123' }).click()
  await page.waitForTimeout(200)
  await shot('ime-02-symbols')
  await page.evaluate(() => window.droid_shell.wm.back())
  await page.waitForTimeout(400)
  console.log('closed on back:', !(await page.locator('#ime.on').count()))
  // a dpk app with a text field
  await page.evaluate(() => window.droid_shell.wm.start({ action: 'install', data: 'examples/notes.dpk', type: 'application/x-dpk' }))
  await page.waitForTimeout(2000)
  await page.click('.pi-buttons .h-btn-borderless:last-child').catch(() => {}); await page.waitForTimeout(1500)
  await page.click('.pi-buttons .h-btn-borderless:last-child').catch(() => {}); await page.waitForTimeout(3000)
  await page.evaluate(() => window.droid_shell.wm.start({ package: 'com.droid.notes', activity: 'edit', extras: { index: -1 } }))
  await page.waitForTimeout(2500)
  const f = page.frameLocator('.window.visible iframe')
  const field = f.locator('input, textarea').first()
  console.log('app fields:', await f.locator('input, textarea').count())
  if (process.env.TOUCH) await field.tap(); else await field.click()
  await page.waitForTimeout(600)
  console.log('ime open:', await page.locator('#ime.on').count(), 'inputmode:', await field.getAttribute('inputmode'))
  for (const c of 'coo') await tap(c)
  await page.waitForTimeout(300)
  console.log('app value:', await field.inputValue())
  await shot('ime-03-app')
}
