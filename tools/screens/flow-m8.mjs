// milestone 8: install the converted test apk (hellojni.dpk) and use it
export default async ({ page, shot, base }) => {
  await page.goto(base + 'index.html?fastboot')
  await page.evaluate(() => localStorage.setItem('droid.settings', JSON.stringify({ 'setup.done': true, 'lock.type': 'none' })))
  await page.reload()
  await page.waitForTimeout(2500)
  await page.evaluate(() => { window.droid_shell.wm.start({ action: 'install', data: 'apk-test/test.apk', type: 'application/vnd.android.package-archive' }) })
  await page.waitForTimeout(2500)
  await shot('m8-01-installer')
  await page.click('.pi-buttons .h-btn-borderless:last-child')
  await page.waitForTimeout(1500)
  await page.click('.pi-buttons .h-btn-borderless:last-child')
  await page.waitForTimeout(3000)
  await shot('m8-02-app')
  const f = page.frameLocator('.window.visible iframe')
  await f.locator('input.h-edit').fill('jhu')
  await f.locator('button.h-btn').first().click()
  await page.waitForTimeout(400)
  await f.locator('button.h-btn').first().click()
  await page.waitForTimeout(600)
  await shot('m8-03-clicked')
  await f.locator('button.h-btn').nth(1).click()
  await page.waitForTimeout(2500)
  await shot('m8-04-second')
}
